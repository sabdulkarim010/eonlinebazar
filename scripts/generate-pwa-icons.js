/**
 * Generates PWA manifest icons at the exact sizes declared in manifest.json.
 * Run: node scripts/generate-pwa-icons.js
 */
const fs = require('fs');
const path = require('path');
const sharp = require('sharp');

const sizes = [72, 96, 128, 144, 152, 192, 384, 512];
const iconsDir = path.join(__dirname, '..', 'public', 'images', 'icons');
const sourceCandidates = [
    path.join(__dirname, '..', 'public', 'images', 'og-default.jpg'),
    path.join(__dirname, '..', 'public', 'images', 'placeholder-product.svg')
];

async function resolveSourceImage() {
    for (const candidate of sourceCandidates) {
        if (fs.existsSync(candidate)) return candidate;
    }
    return null;
}

async function generateIcons() {
    fs.mkdirSync(iconsDir, { recursive: true });

    const source = await resolveSourceImage();
    if (!source) {
        throw new Error('No source image found for PWA icon generation.');
    }

    for (const size of sizes) {
        const outputPath = path.join(iconsDir, `icon-${size}x${size}.png`);
        await sharp(source)
            .resize(size, size, { fit: 'cover', position: 'centre' })
            .png()
            .toFile(outputPath);
    }

    fs.writeFileSync(
        path.join(iconsDir, 'README.txt'),
        'Generated by scripts/generate-pwa-icons.js from og-default.jpg.\n' +
            'Re-run the script after updating the source artwork.\n'
    );

    const verify = await sharp(path.join(iconsDir, 'icon-144x144.png')).metadata();
    console.log(`Created ${sizes.length} icons in public/images/icons/`);
    console.log(`Verified icon-144x144.png: ${verify.width}x${verify.height}`);
}

generateIcons().catch((err) => {
    console.error(err);
    process.exit(1);
});

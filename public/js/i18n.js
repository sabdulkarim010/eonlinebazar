let currentLang = localStorage.getItem('eonlinebazar_lang') || 'bn';

function t(key, vars = {}) {
  const text = translations[currentLang]?.[key] || translations['bn'][key] || key;
  return text.replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? '');
}

function updateLangLabel() {
  document.querySelectorAll('#lang-label').forEach((el) => {
    el.textContent = currentLang === 'bn' ? 'EN' : 'বাং';
  });
}

function setLanguage(lang) {
  currentLang = lang;
  localStorage.setItem('eonlinebazar_lang', lang);
  applyTranslations();
  document.documentElement.lang = lang === 'bn' ? 'bn' : 'en';
  updateLangLabel();
  document.dispatchEvent(new CustomEvent('languageChanged', { detail: { lang } }));
}

function getCurrentLang() { return currentLang; }

function applyTranslations() {
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.getAttribute('data-i18n');
    el.textContent = t(key);
  });

  document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    el.placeholder = t(el.getAttribute('data-i18n-placeholder'));
  });

  document.querySelectorAll('[data-i18n-aria]').forEach((el) => {
    el.setAttribute('aria-label', t(el.getAttribute('data-i18n-aria')));
  });
}

function formatCurrency(amount) {
  if (currentLang === 'bn') {
    return '৳' + Number(amount).toLocaleString('bn-BD');
  }
  return '৳' + Number(amount).toLocaleString('en-US');
}

function formatDate(date) {
  return new Date(date).toLocaleDateString(
    currentLang === 'bn' ? 'bn-BD' : 'en-US',
    { year: 'numeric', month: 'long', day: 'numeric' }
  );
}

window.i18n = { t, setLanguage, getCurrentLang, applyTranslations, formatCurrency, formatDate };

document.addEventListener('languageChanged', (e) => {
  document.querySelectorAll('#lang-label').forEach((el) => {
    el.textContent = e.detail.lang === 'bn' ? 'EN' : 'বাং';
  });
});

function bootstrapI18n() {
  document.documentElement.lang = currentLang === 'bn' ? 'bn' : 'en';
  applyTranslations();
  updateLangLabel();
}

if (document.readyState === 'loading') {
  document.addEventListener('DOMContentLoaded', bootstrapI18n);
} else {
  bootstrapI18n();
}
